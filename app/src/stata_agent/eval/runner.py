def _scenario_l1_tool_routing() -> dict[str, Any]:
    """Verify policy choices and the central enforcer's hard denials."""

    tools = default_tools()
    enforcer = ToolEnforcer(tools)
    estimation = ToolContext(
        idea="eval-l1",
        phase=Phase.ESTIMATION.value,
        privacy_mode=APPROVED_REMOTE,
        network_available=True,
    )
    done = ToolContext(
        idea="eval-l1",
        phase=Phase.DONE.value,
        privacy_mode=APPROVED_REMOTE,
        network_available=True,
    )
    return {
        "policy": {
            "request_run_in_estimation": check_act(
                "request_run", phase=Phase.ESTIMATION
            ).result,
            "mark_done": check_act("mark_done").result,
            "web_in_local_strict": check_act(
                "web_search", privacy_mode=LOCAL_STRICT
            ).result,
            "spec_change_in_formal": check_act(
                "propose_spec",
                phase=Phase.DESIGN,
                gate_mode=GateMode.FORMAL,
                is_research_change=True,
            ).result,
        },
        "enforcer": {
            "unknown_tool_rejected": enforcer.validate("not_registered", {}, estimation)
            is not None,
            "missing_required_argument_rejected": enforcer.validate(
                "run_stata", {}, estimation
            )
            is not None,
            "private_url_rejected": enforcer.validate(
                "fetch_source", {"url": "http://127.0.0.1:8000/health"}, estimation
            )
            is not None,
            "execute_in_done_rejected": enforcer.validate(
                "run_stata", {"code": "display 1"}, done
            )
            is not None,
            "registered_tools_exposed": all(
                name in tools for name in ("run_stata", "write_draft", "ask_user")
            ),
        },
    }


def _uncertain_chain(store: SQLiteStore, *, idea: str, run_id: str, operation_id: str) -> None:
    """Append a deterministic uncertain execution chain for the recovery case."""

    store.append_many(
        [
            Event(
                idea_id=idea,
                event_type=EVENT_RUN_REQ,
                actor=ACTOR_ORCH,
                source=ACTOR_ORCH,
                operation_id=operation_id,
                attempt_id=1,
                fingerprint=f"eval-{operation_id}",
                payload={
                    "run_id": run_id,
                    "side_effect": "write",
                    "semantic_input_hash": f"eval-{operation_id}",
                },
            ),
            Event(
                idea_id=idea,
                event_type=EVENT_TOOL_CALL,
                actor=ACTOR_ORCH,
                source=ACTOR_ORCH,
                operation_id=operation_id,
                payload={"run_id": run_id, "call_id": f"call-{operation_id}"},
            ),
            Event(
                idea_id=idea,
                event_type=EVENT_TOOL_RESULT,
                actor=ACTOR_ORCH,
                source=ACTOR_ORCH,
                operation_id=operation_id,
                payload={
                    "run_id": run_id,
                    "call_id": f"call-{operation_id}",
                    "transport_error": True,
                },
            ),
            Event(
                idea_id=idea,
                event_type=EVENT_RUN_UNCERTAIN,
                actor=ACTOR_ORCH,
                source=ACTOR_ORCH,
                operation_id=operation_id,
                attempt_id=1,
                payload={"run_id": run_id, "reason": "transport timeout"},
            ),
        ]
    )


def _scenario_l2_run_fsm_recovery() -> dict[str, Any]:
    """Verify valid run closure, invalid transition rejection, and recovery."""

    with TemporaryDirectory(prefix="stata-agent-eval-") as raw_dir:
        root = Path(raw_dir)
        store = SQLiteStore(str(root / "fsm.sqlite3"), writer_id="eval-fsm")
        try:
            FakeExecutor(store).execute("display 1", idea="eval-fsm", run_id="eval-fsm")
            valid_events = [event.event_type for event in store.scan("eval-fsm")]
            valid_projection = store.project("eval-fsm")

            invalid_store = SQLiteStore(
                str(root / "invalid.sqlite3"), writer_id="eval-invalid"
            )
            try:
                invalid_store.append(
                    Event(
                        idea_id="eval-invalid",
                        event_type=EVENT_RUN_REQ,
                        actor=ACTOR_ORCH,
                        source=ACTOR_ORCH,
                        operation_id="op-invalid",
                        fingerprint="eval-invalid",
                        payload={"run_id": "run-invalid"},
                    )
                )
                try:
                    invalid_store.append(
                        Event(
                            idea_id="eval-invalid",
                            event_type=EVENT_RUN_SUCCEEDED,
                            actor=ACTOR_ORCH,
                            source=ACTOR_ORCH,
                            operation_id="op-invalid",
                            payload={"run_id": "run-invalid"},
                        )
                    )
                except IllegalEventSequence:
                    invalid_transition_rejected = True
                else:
                    invalid_transition_rejected = False
                invalid_event_count = sum(1 for _ in invalid_store.scan("eval-invalid"))
            finally:
                invalid_store.close()

            recovery_store = SQLiteStore(
                str(root / "recovery.sqlite3"), writer_id="eval-recovery"
            )
            try:
                _uncertain_chain(
                    recovery_store,
                    idea="eval-recovery",
                    run_id="eval-uncertain",
                    operation_id="op-uncertain",
                )
                first = reconcile_uncertain(recovery_store, "eval-recovery")
                second = reconcile_uncertain(recovery_store, "eval-recovery")
                recovery_events = [event.event_type for event in recovery_store.scan("eval-recovery")]
                restored_count = sum(
                    1 for event in recovery_store.scan("eval-recovery", event_types={EVENT_RESTORED})
                )
            finally:
                recovery_store.close()
        finally:
            store.close()

    return {
        "valid_trace": valid_events,
        "valid_run_status": valid_projection.runs["eval-fsm"].status,
        "invalid_terminal_rejected": invalid_transition_rejected,
        "invalid_event_count_after_rejection": invalid_event_count,
        "uncertain_trace": recovery_events,
        "recovery_first": first,
        "recovery_second_same": first == second,
        "restored_event_count": restored_count,
    }


def _scenario_l3_evidence_grounding() -> dict[str, Any]:
    """Verify machine values become cards/claim and text cannot add numbers."""

    with TemporaryDirectory(prefix="stata-agent-eval-") as raw_dir:
        root = Path(raw_dir)
        store = SQLiteStore(str(root / "evidence.sqlite3"), writer_id="eval-evidence")
        try:
            FakeExecutor(store).execute(
                "display 1", idea="eval-evidence", run_id="eval-evidence"
            )
            signed = sign_run_numeric_cards(
                store,
                "eval-evidence",
                idea="eval-evidence",
                claim_statement="主回归结果已验证",
            )
            projection = store.project("eval-evidence")
            claim = projection.claims["claim-eval-evidence"]
            cards = [projection.cards[card_id] for card_id in claim.cards]
            sentence = render_claim_sentence(claim, projection.cards)
            tampered_tokens = validate_sentence(
                "主回归系数=-238.800，样本量=80。", cards
            )
            draft = draft_from_ledger(projection, title="评测初稿")
            from docx import Document

            document = Document(BytesIO(draft))
            paragraphs = [paragraph.text for paragraph in document.paragraphs]
        finally:
            store.close()

    return {
        "machine_keys": sorted(projection.runs["eval-evidence"].machine),
        "signed_card_ids": sorted(signed),
        "claim_id": claim.claim_id,
        "claim_card_count": len(claim.cards),
        "sentence_numbers_grounded": validate_sentence(sentence, cards) == [],
        "tampered_numbers_detected": sorted(tampered_tokens),
        "draft_has_claim": any("主回归结果已验证" in text for text in paragraphs),
        "draft_nonempty": bool(draft),
    }


class _DeterministicChatProvider:
    """Three-turn local provider used only by the offline L4 scenario."""

    provider = "local"

    def __init__(self) -> None:
        self._index = 0

    def chat(self, messages: list[dict[str, Any]], *, tools: list[dict[str, Any]]) -> dict[str, Any]:
        del messages, tools
        self._index += 1
        if self._index == 1:
            return {
                "content": None,
                "tool_calls": [
                    {
                        "id": "eval-call-run",
                        "name": "run_stata",
                        "arguments": {"code": "display 1"},
                    }
                ],
            }
        if self._index == 2:
            return {
                "content": None,
                "tool_calls": [
                    {
                        "id": "eval-call-draft",
                        "name": "write_draft",
                        "arguments": {"method": "评测方法", "limits": ""},
                    }
                ],
            }
        return {"content": "评测链路完成。", "tool_calls": []}


class _FixedFakeExecutor(FakeExecutor):
    """Keep the run identifier stable when the toolkit invokes the executor."""

    def execute(self, script: str, **kwargs: Any) -> dict[str, Any]:
        kwargs.setdefault("run_id", "eval-chain")
        return super().execute(script, **kwargs)


def _scenario_l4_fake_to_draft() -> dict[str, Any]:
    """Exercise message -> tool -> Fake -> cards -> claim -> draft."""

    with TemporaryDirectory(prefix="stata-agent-eval-") as raw_dir:
        root = Path(raw_dir)
        run_root = root / "runs"
        run_root.mkdir(parents=True, exist_ok=True)
        store = SQLiteStore(str(root / "chain.sqlite3"), writer_id="eval-chain")
        try:
            store.append(
                Event(
                    idea_id="eval-chain",
                    event_type=EVENT_IDEA,
                    actor=ACTOR_AGENT,
                    source=ACTOR_AGENT,
                    payload={"question": "跑主回归"},
                )
            )
            store.append(
                Event(
                    idea_id="eval-chain",
                    event_type=EVENT_PHASE,
                    actor=ACTOR_ORCH,
                    source=ACTOR_ORCH,
                    payload={"from": "IDEA", "to": "ESTIMATION"},
                )
            )
            store.append(
                Event(
                    idea_id="eval-chain",
                    event_type="user.message",
                    actor=ACTOR_USER,
                    source=ACTOR_USER,
                    payload={"text": "跑主回归"},
                )
            )
            ctx = ToolContext(
                idea="eval-chain",
                store=store,
                executor=_FixedFakeExecutor(store),
                run_root=run_root,
                phase=Phase.ESTIMATION.value,
                privacy_mode=LOCAL_STRICT,
                allowed_roots=(root,),
            )
            result = run_loop(
                store,
                _DeterministicChatProvider(),
                default_tools(),
                ctx,
                user_text="跑主回归",
                max_steps=4,
                max_tool_calls=4,
            )
            events = list(store.scan("eval-chain"))
            projection = store.project("eval-chain")
            draft_path = run_root / "eval-chain_draft.docx"
            from docx import Document

            draft_paragraphs = []
            draft_written = draft_path.is_file()
            if draft_written:
                draft_paragraphs = [
                    paragraph.text for paragraph in Document(str(draft_path)).paragraphs
                ]
        finally:
            store.close()

    trace = [event.event_type for event in events if event.event_type in _TRACE_EVENTS]
    return {
        "trace": trace,
        "tool_calls": result.tool_calls,
        "run_status": projection.runs["eval-chain"].status,
        "card_count": len(projection.cards),
        "claim_count": len(projection.claims),
        "draft_written": draft_written,
        "draft_has_claim": any("run eval-chain 结果已入证据链" in text for text in draft_paragraphs),
    }


SCENARIOS: dict[str, Callable[[], dict[str, Any]]] = {
    "L1_TOOL_ROUTING": _scenario_l1_tool_routing,
    "L2_RUN_FSM_RECOVERY": _scenario_l2_run_fsm_recovery,
    "L3_EVIDENCE_GROUNDING": _scenario_l3_evidence_grounding,
    "L4_FAKE_TO_DRAFT": _scenario_l4_fake_to_draft,
}


def _golden_candidates() -> tuple[Path, ...]:
    source = Path(__file__).resolve().parents[3] / "eval_golden" / _SCENARIO_GOLDEN
    packaged = Path(__file__).with_name("golden.json")
    return source, packaged


def load_golden() -> dict[str, Any]:
    """Load the checkout golden, or the copy bundled in a wheel."""

    for path in _golden_candidates():
        if path.is_file():
            payload = json.loads(path.read_text(encoding="utf-8"))
            if not isinstance(payload, dict) or payload.get("schema_version") != SCHEMA_VERSION:
                raise ValueError(f"golden schema_version 必须为 {SCHEMA_VERSION}: {path}")
            scenarios = payload.get("scenarios")
            if not isinstance(scenarios, dict):
                raise ValueError(f"golden 缺少 scenarios object: {path}")
            return payload
    raise FileNotFoundError("找不到 eval_golden/scenarios.json 或打包的 eval/golden.json")


def _diff(expected: Any, actual: Any, path: str = "") -> list[str]:
    """Return deterministic, compact differences for JSON-like values."""

    if isinstance(expected, dict) and isinstance(actual, dict):
        differences: list[str] = []
        for key in sorted(set(expected) | set(actual)):
            child = f"{path}.{key}" if path else str(key)
            if key not in expected:
                differences.append(f"{child}: unexpected")
            elif key not in actual:
                differences.append(f"{child}: missing")
            else:
                differences.extend(_diff(expected[key], actual[key], child))
        return differences
    if isinstance(expected, list) and isinstance(actual, list):
        if expected == actual:
            return []
        return [f"{path}: expected {expected!r}, got {actual!r}"]
    if expected != actual:
        return [f"{path}: expected {expected!r}, got {actual!r}"]
    return []


def run_product_eval(names: list[str] | None = None) -> dict[str, Any]:
    """Run selected scenarios and return a machine-readable report."""

    selected = names or list(SCENARIO_ORDER)
    unknown = sorted(set(selected) - set(SCENARIOS))
    if unknown:
        raise ValueError(f"未知 scenario: {', '.join(unknown)}")
    golden = load_golden().get("scenarios", {})
    reports: dict[str, Any] = {}
    for name in selected:
        try:
            observed = SCENARIOS[name]()
            expected = golden.get(name)
            if not isinstance(expected, dict):
                raise ValueError(f"golden 缺少 scenario: {name}")
            differences = _diff(expected, observed)
            reports[name] = {
                "ok": not differences,
                "observed": observed,
                "failures": differences,
            }
        except Exception as error:  # noqa: BLE001 - report each gate, do not hide others
            reports[name] = {
                "ok": False,
                "observed": {},
                "failures": [f"{type(error).__name__}: scenario execution failed"],
            }
    passed = sum(1 for report in reports.values() if report["ok"])
    total = len(reports)
    return {
        "schema_version": SCHEMA_VERSION,
        "ok": passed == total,
        "summary": {"total": total, "passed": passed, "failed": total - passed},
        "scenarios": reports,
    }


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="stata-agent-eval",
        description="运行离线、确定性的 stata-agent 产品评测 scenarios",
    )
    parser.add_argument(
        "--scenario",
        action="append",
        choices=SCENARIO_ORDER,
        help="只运行一个 scenario；可重复传入，默认运行全部",
    )
    parser.add_argument(
        "--json",
        action="store_true",
        help="只输出机器可读 JSON（CI 推荐）",
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    parser = _parser()
    args = parser.parse_args(argv)
    try:
        report = run_product_eval(args.scenario)
    except Exception as error:  # noqa: BLE001 - CLI converts setup failures to exit 2
        if args.json:
            print(
                json.dumps(
                    {
                        "schema_version": SCHEMA_VERSION,
                        "ok": False,
                        "summary": {"total": 0, "passed": 0, "failed": 0},
                        "error": type(error).__name__,
                    },
                    ensure_ascii=False,
                    sort_keys=True,
                )
            )
        else:
            print(f"product-eval setup failed: {error}", file=sys.stderr)
        return 2
    if args.json:
        print(json.dumps(report, ensure_ascii=False, sort_keys=True))
    else:
        summary = report["summary"]
        print(
            f"product-eval: {summary['passed']}/{summary['total']} scenarios passed"
        )
        for name, item in report["scenarios"].items():
            status = "PASS" if item["ok"] else "FAIL"
            print(f"  {status} {name}")
            for failure in item["failures"]:
                print(f"    - {failure}")
    return 0 if report["ok"] else 1


