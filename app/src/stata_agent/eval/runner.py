"""Offline product-evaluation scenarios and their command-line runner.

The product-eval command intentionally exercises the public seams that make a
research run trustworthy: policy/tool routing, the append-only run FSM,
uncertain recovery, evidence grounding, and the complete fake execution chain
through a draft.  It never needs Stata, a model key, a network connection, or
the user's data.

Scenario output is a small JSON document containing only stable fields.  UUIDs,
timestamps, temporary directories, and generated byte counts are deliberately
left out so a golden trace can be compared across machines and runs.
"""

