def _l5_append_messages(store: SQLiteStore, idea: str, start: int, count: int) -> None:
    """Append ordinary narrative turns with stable, non-sensitive payloads."""

    events: list[Event] = []
    for index in range(start, start + count):
        events.extend(
            [
                Event(
                    idea_id=idea,
                    event_type=EVENT_USER,
                    actor=ACTOR_USER,
                    source=ACTOR_USER,
                    payload={"text": f"L5 session turn {index}: preserve the research objective."},
                ),
                Event(
                    idea_id=idea,
                    event_type=EVENT_AGENT_STEP,
                    actor=ACTOR_AGENT,
                    source=ACTOR_AGENT,
                    payload={
                        "reply": f"L5 deterministic acknowledgement {index}.",
                        "decision_summary": "保留研究目标和研究状态。" if index % 7 == 0 else "",
                    },
                ),
            ]
        )
    store.append_many(events)


