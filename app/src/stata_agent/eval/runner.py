def load_golden() -> dict[str, Any]:
    """Load the checkout golden, or the copy bundled in a wheel."""

    for path in _golden_candidates():
        if path.is_file():
            payload = json.loads(path.read_text(encoding="utf-8"))
            if not isinstance(payload, dict) or payload.get("schema_version") != SCHEMA_VERSION:
                raise ValueError(f"golden schema_version 必须为 {SCHEMA_VERSION}: {path}")
            scenarios = payload.get("scenarios")
            if not isinstance(scenarios, dict):
                raise ValueError(f"golden 缺少 scenarios object: {path}")
            return payload
    raise FileNotFoundError("找不到 eval_golden/scenarios.json 或打包的 eval/golden.json")


def _diff(expected: Any, actual: Any, path: str = "") -> list[str]:
    """Return deterministic, compact differences for JSON-like values."""

    if isinstance(expected, dict) and isinstance(actual, dict):
        differences: list[str] = []
        for key in sorted(set(expected) | set(actual)):
            child = f"{path}.{key}" if path else str(key)
            if key not in expected:
                differences.append(f"{child}: unexpected")
            elif key not in actual:
                differences.append(f"{child}: missing")
            else:
                differences.extend(_diff(expected[key], actual[key], child))
        return differences
    if isinstance(expected, list) and isinstance(actual, list):
        if expected == actual:
            return []
        return [f"{path}: expected {expected!r}, got {actual!r}"]
    if expected != actual:
        return [f"{path}: expected {expected!r}, got {actual!r}"]
    return []


def run_product_eval(names: list[str] | None = None) -> dict[str, Any]:
    """Run selected scenarios and return a machine-readable report."""

    selected = names or list(SCENARIO_ORDER)
    unknown = sorted(set(selected) - set(SCENARIOS))
    if unknown:
        raise ValueError(f"未知 scenario: {', '.join(unknown)}")
    golden = load_golden().get("scenarios", {})
    reports: dict[str, Any] = {}
    for name in selected:
        try:
            observed = SCENARIOS[name]()
            expected = golden.get(name)
            if not isinstance(expected, dict):
                raise ValueError(f"golden 缺少 scenario: {name}")
            differences = _diff(expected, observed)
            reports[name] = {
                "ok": not differences,
                "observed": observed,
                "failures": differences,
            }
        except Exception as error:  # noqa: BLE001 - report each gate, do not hide others
            reports[name] = {
                "ok": False,
                "observed": {},
                "failures": [f"{type(error).__name__}: scenario execution failed"],
            }
    passed = sum(1 for report in reports.values() if report["ok"])
    total = len(reports)
    return {
        "schema_version": SCHEMA_VERSION,
        "ok": passed == total,
        "summary": {"total": total, "passed": passed, "failed": total - passed},
        "scenarios": reports,
    }


