def _l5_memory_signature(selection: Any) -> tuple[Any, ...]:
    """Compare facades by stable content/provenance, never random UUIDs."""

    return tuple(
        (
            str(record.get("text", "")),
            str(record.get("kind", "")),
            tuple(str(source) for source in record.get("source_ids", []) or []),
            str(record.get("status", "")),
        )
        for record in selection
    ) + (tuple(selection.formatted), bool(selection.truncated))


