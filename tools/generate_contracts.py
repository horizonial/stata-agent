def build_ipc_schema() -> dict[str, Any]:
    return {
        "schema_version": "1",
        "main_to_worker": TypeAdapter(WorkerIpcInput).json_schema(),
        "worker_to_main": TypeAdapter(AgentIpcMessage).json_schema(),
    }


def build_tool_schema() -> dict[str, Any]:
    return {
        "schema_version": "1",
        "schemas": {
            model.__name__: model.model_json_schema()
            for model in (
                CanonicalToolCallEnvelope,
                OperationEnvelope,
                OperationAttemptEnvelope,
                CompletionManifestEnvelope,
                CanonicalToolResultEnvelope,
            )
        },
    }


def main() -> None:
    with tempfile.TemporaryDirectory(prefix="stata-agent-contract-") as temporary:
        app = create_app(WorkspaceHost(Path(temporary)))
        openapi = app.openapi()
    write_json(ROOT / "contracts" / "api" / "openapi-v1.json", openapi)
    write_json(
        ROOT / "contracts" / "ipc" / "agent-ipc-v2.schema.json",
        build_ipc_schema(),
    )
    write_json(
        ROOT / "contracts" / "tools" / "tool-contract-v1.schema.json",
        build_tool_schema(),
    )
    generated = ROOT / "web" / "src" / "generated" / "api-v1.ts"
    generated.parent.mkdir(parents=True, exist_ok=True)
    generated.write_text(generate_typescript(openapi), encoding="utf-8")


