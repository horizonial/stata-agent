def write_json(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )


def schema_to_ts(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(item) for item in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(schema_to_ts(item) for item in schema["anyOf"])
    if "oneOf" in schema:
        return " | ".join(schema_to_ts(item) for item in schema["oneOf"])
    schema_type = schema.get("type")
    if isinstance(schema_type, list):
        return " | ".join(schema_to_ts({**schema, "type": item}) for item in schema_type)
    if schema_type == "string":
        return "string"
    if schema_type in {"integer", "number"}:
        return "number"
    if schema_type == "boolean":
        return "boolean"
    if schema_type == "null":
        return "null"
    if schema_type == "array":
        return f"ReadonlyArray<{schema_to_ts(schema.get('items', {}))}>"
    if schema_type == "object" or "properties" in schema:
        properties = schema.get("properties", {})
        additional = schema.get("additionalProperties")
        if not properties and additional is not None:
            if additional is False:
                return "Readonly<Record<string, never>>"
            value_type = "unknown" if additional is True else schema_to_ts(additional)
            return f"Readonly<Record<string, {value_type}>>"
        required = set(schema.get("required", []))
        fields = []
        for name, field_schema in sorted(properties.items()):
            optional = "" if name in required else "?"
            fields.append(f"  readonly {json.dumps(name)}{optional}: {schema_to_ts(field_schema)};")
        if not fields:
            return "Readonly<Record<string, never>>"
        return "{\n" + "\n".join(fields) + "\n}"
    return "unknown"


